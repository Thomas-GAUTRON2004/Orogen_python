def test_hypot3_special_values_match_v8():
    assert _hypot3(0.0, 0.0, 0.0) == 0
    assert _hypot3(1e300, 1e300, 1e300) == 1.7320508075688774e+300
    assert _hypot3(3.0, 4.0, 12.0) == 13
